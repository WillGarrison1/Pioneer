def ToBytes(psqt: str):
    ranks = psqt.split(",\n")
    nums = []
    for rank in ranks:
        vals = rank.split(",")
        num = 0
        for val in vals:
            num <<= 8
            valByte = int(val).to_bytes(1, signed=True)
            num |= int.from_bytes(valByte, signed=False)
        nums.append(num)

    return nums


